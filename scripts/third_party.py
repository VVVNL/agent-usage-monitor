#!/usr/bin/env python3
"""Generate docs/THIRD_PARTY.md from the Windows and macOS dependency trees.

Usage: python3 scripts/third_party.py            (writes docs/THIRD_PARTY.md)
Run from the repository root; needs `cargo` on PATH.
"""
import subprocess, sys, collections

TARGETS = ["x86_64-pc-windows-gnu", "aarch64-apple-darwin"]
out = "\n".join(
    subprocess.run(
        ["cargo", "tree", "-p", "aum-app", "--target", t, "-e", "normal",
         "--prefix", "none", "--format", "{p}|{l}"],
        capture_output=True, text=True, check=True).stdout
    for t in TARGETS)

pkgs = {}
for line in out.splitlines():
    line = line.strip()
    if not line or "|" not in line:
        continue
    pkg, lic = line.split("|", 1)
    name = pkg.split(" ")[0]
    ver = pkg.split(" ")[1].lstrip("v") if " " in pkg else ""
    if name.startswith("aum-") or name.startswith("aum_"):
        continue
    pkgs[(name, ver)] = lic.strip() or "UNKNOWN"

# Flag anything that is not clearly permissive.
PERMISSIVE = ("MIT", "Apache-2.0", "BSD", "ISC", "Zlib", "Unicode", "CC0", "Unlicense", "MPL-2.0", "0BSD", "BSL-1.0", "OFL", "Ubuntu")
def permissive_option(lic):
    # An SPDX "OR" expression is satisfied by any permissive alternative.
    alts = [a.strip(" ()") for a in lic.replace(" OR ", "|").replace("/", "|").split("|")]
    return any(any(p in a for p in PERMISSIVE) for a in alts)

by_lic = collections.defaultdict(list)
for (n, v), l in sorted(pkgs.items()):
    by_lic[l].append(f"{n} {v}")
flag = {l for l in by_lic if not permissive_option(l)}

lines = ["# Third-party software", "",
         "Generated by `scripts/third_party.py` from the Windows and macOS dependency trees. "
         "Regenerate before each release.", "",
         f"{len(pkgs)} crates, {len(by_lic)} distinct licence expressions.", ""]
if flag:
    lines += ["## Needs attention", ""]
    for l in sorted(flag):
        lines.append(f"- **{l}**: " + ", ".join(by_lic[l]))
    lines.append("")
lines += ["## All licences", ""]
for l in sorted(by_lic, key=lambda k: (-len(by_lic[k]), k)):
    lines.append(f"### {l} ({len(by_lic[l])})")
    lines.append("")
    lines.append(", ".join(by_lic[l]))
    lines.append("")
open("docs/THIRD_PARTY.md", "w").write("\n".join(lines))
print(f"{len(pkgs)} crates; flagged: {sorted(flag) if flag else 'none'}")
